"""Build the simulation assets for the Open G1 servo arms from the hardware repo.

Reads the finished arm STLs (github.com/open3dhumanoid/humanoid, folder STL/arms) and writes
  * src/openG1/assets/mesh/og1_{side}_{link}.STL - one sim mesh per arm body, in metres, in the
        MuJoCo body (= G1 link) frame: the printed link plus every actuator part that rides on it
        (servo cartridge, cap / back cap, horn plate, idler pin, shoulder-pitch horn hub)
  * tools/arm_mass.json - mass, centre of mass and inertia of every arm body, left and right

usage:  python tools/arms/build_sim_arms.py /path/to/humanoid/STL

Where each part sits is read from STL/arms/arm_assembly.scad (the same placements the OpenSCAD
assembly uses), so this script never needs to know the design rules.

Mass model (edit the constants if you weigh your parts):
  printed parts   0.56 g/cm3 effective (PLA, ~45 % solid; same as the legs and torso)
  servos          SERVO_G below, placed at the centre of the servo's cartridge in its host link
  bearings        BEARING_G below, in the host link
  fasteners       FASTENER_G per joint (inserts + screws), at the cartridge
  rubber hand     assets/mesh/{side}_rubber_hand_open3d.STL at the printed density, in the wrist yaw link
The shoulder-pitch servo sits in the torso shoulder block and is counted in the torso mass.
"""
import json
import re
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "legs"))
from build_sim_legs import RHO, combine, load_stl, mass_props, reduce, save_stl  # noqa: E402

GYM = Path(__file__).resolve().parents[2]
OUT_MESH = GYM / "src" / "openG1" / "assets" / "mesh"
OUT_JSON = GYM / "tools" / "arm_mass.json"

LINKS = ["shoulder_pitch_link", "shoulder_roll_link", "shoulder_yaw_link", "elbow_link",
         "wrist_roll_link", "wrist_pitch_link", "wrist_yaw_link"]
# servo masses in grams (data-sheet values; weigh yours)
SERVO_G = {"std": 65.0,      # 40x20 standard servo, DS3235 / DS3218
           "micro": 14.0}    # 23x12 micro servo, MG90S / MG92B
BEARING_G = {"6803": 8.0, "6805": 20.0}
FASTENER_G = 4.0
# joint -> (host link that holds the servo cartridge, servo size, bearing)
JOINTS = {"shoulder_roll": ("shoulder_pitch_link", "std", "6803"),
          "shoulder_yaw": ("shoulder_roll_link", "micro", "6805"),
          "elbow": ("shoulder_yaw_link", "std", None),
          "wrist_roll": ("elbow_link", "micro", "6805"),
          "wrist_pitch": ("wrist_pitch_link", "micro", "6803"),
          "wrist_yaw": ("wrist_pitch_link", "micro", "6803")}


def parse_assembly(scad):
    """{(side, link): [(stl path relative to STL/arms, 4x4 matrix in the link frame), ...]}"""
    txt = Path(scad).read_text()
    out = {}
    for side in ("left", "right"):
        for link in LINKS:
            m = re.search(r"module %s_%s\(\)\{(.*?)\n\}" % (side, link), txt, re.S)
            if not m:
                raise SystemExit(f"{scad}: no module {side}_{link}")
            body = m.group(1).split("\n", 1)[1]          # skip the joint transform line
            parts = []
            for line in body.splitlines():
                imp = re.search(r'import\("([^"]+)"', line)
                if not imp:
                    continue
                mm = re.search(r"multmatrix\((\[\[.*?\]\])\)", line)
                M = np.array(eval(mm.group(1))) if mm else np.eye(4)
                parts.append((imp.group(1), M))
            out[(side, link)] = parts
    return out


def placed(tri, M):
    t = tri @ M[:3, :3].T + M[:3, 3]
    if np.linalg.det(M[:3, :3]) < 0:                   # mirrored placement: keep the mesh outward-facing
        t = t[:, ::-1]
    return t


def main(stl):
    arms = Path(stl) / "arms"
    asm = parse_assembly(arms / "arm_assembly.scad")
    OUT_MESH.mkdir(parents=True, exist_ok=True)
    out = {"_note": "generated by tools/arms/build_sim_arms.py; kg, m, kg m^2, in each body frame; "
                    f"printed parts at {RHO * 1e3:.2f} g/cm3 + servos {SERVO_G} g + bearings {BEARING_G} g"}
    for side in ("left", "right"):
        for link in LINKS:
            tris, items, cart = [], [], {}
            for rel, M in asm[(side, link)]:
                tri = placed(load_stl(arms / rel), M)
                pr = mass_props(tri)
                if pr[0] <= 0:
                    raise SystemExit(f"{rel}: mesh is inside-out or open (volume {pr[0]})")
                tris.append(tri)
                items.append(pr)
                name = Path(rel).stem
                if name.endswith("_cartridge"):
                    cart[name[len(side) + 1:-len("_cartridge")]] = pr[1]
            printed = sum(i[0] for i in items)
            extras = []
            for joint, (host, size, bearing) in JOINTS.items():
                if host != link:
                    continue
                c = cart[joint]
                extras.append((SERVO_G[size] + FASTENER_G + (BEARING_G[bearing] if bearing else 0.0), c, np.zeros((3, 3))))
            if link == "wrist_yaw_link":                 # the rubber hand is its own geom but rides on this body
                extras.append(mass_props(load_stl(OUT_MESH / f"{side}_rubber_hand_open3d.STL") * 1000))
            m, c, I = combine(items + extras)
            mesh = np.concatenate(tris)
            red = reduce(mesh)
            save_stl(OUT_MESH / f"og1_{side}_{link}.STL", red / 1000)
            out[f"{side}_{link}"] = dict(mass=m / 1000, com=(c / 1000).tolist(), I=(I * 1e-9).tolist(),
                                         printed_mass=printed / 1000, servos=[j for j, v in JOINTS.items() if v[0] == link],
                                         parts=[Path(p).name for p, _ in asm[(side, link)]])
            print(f"  {side}_{link:20s} {m / 1000:.3f} kg  ({printed / 1000:.3f} printed, {len(red)} faces)")
    json.dump(out, open(OUT_JSON, "w"), indent=1)
    print(f"written {OUT_JSON}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "../humanoid/STL")
